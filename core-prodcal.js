/** Рабочий ли это день по производственному календарю (без учёта отпуска). */
export function isWorkday(ds) {
  if (WORK_SAT.has(ds)) return true;
  const w = D(ds).getDay();
  if (w === 0 || w === 6) return false;
  if (KNOWN_YEARS.includes(+ds.slice(0, 4))) return !OFF.has(ds);
  return !FIXED.includes(ds.slice(5));
}
export function holidayName(ds) {
  if (NAMES[ds.slice(5)]) return NAMES[ds.slice(5)];
  const w = D(ds).getDay();
  if (w !== 0 && w !== 6 && !isWorkday(ds)) return 'Перенесённый выходной';
  return '';
}
